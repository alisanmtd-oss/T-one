DATA_CONTRACT_VERSION = "global-commerce-data-contract-v1.1"


def field(name: str, field_type: str, *, required: bool = False, description: str = "") -> dict[str, Any]:
    return {
        "name": name,
        "type": field_type,
        "required": required,
        "description": description,
    }


def contract(
    name: str,
    prefix: str,
    purpose: str,
    fields: list[dict[str, Any]],
    *,
    primary_key: str,
    foreign_keys: dict[str, str] | None = None,
    unique_keys: list[list[str]] | None = None,
    partition_by: list[str] | None = None,
    retention: str = "keep_indefinitely",
    data_layer: str = "silver",
    status_machine: list[str] | None = None,
    sample_json: dict[str, Any] | None = None,
    extensions: list[str] | None = None,
) -> dict[str, Any]:
    layer_paths = DATA_LAYER_PATHS[data_layer]
    return {
        "table": name,
        "id_prefix": prefix,
        "purpose": purpose,
        "data_layer": data_layer,
        "write_path": layer_paths["write_path"],
        "read_path": layer_paths["read_path"],
        "fields": fields,
        "primary_key": primary_key,
        "foreign_keys": foreign_keys or {},
        "unique_keys": unique_keys or [[primary_key]],
        "dedupe_rule": "Use the first matching unique key; if no unique key is complete, keep as unverified raw data.",
        "partition_by": partition_by or ["created_date"],
        "retention": retention,
        "status_machine": status_machine or ["active", "archived"],
        "sample_json": sample_json or {},
        "future_extensions": extensions or [],
    }


