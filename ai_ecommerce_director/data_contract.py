def validate_contract_payload(table_name: str, payload: dict[str, Any]) -> dict[str, Any]:
    table = contract_for(table_name)
    required_fields = [item["name"] for item in table["fields"] if item.get("required")]
    missing = [name for name in required_fields if payload.get(name) in (None, "")]
    return {
        "table": table["table"],
        "version": DATA_CONTRACT_VERSION,
        "valid": not missing,
        "missing_required_fields": missing,
        "primary_key": table["primary_key"],
        "unique_keys": table["unique_keys"],
        "data_layer": table["data_layer"],
    }
