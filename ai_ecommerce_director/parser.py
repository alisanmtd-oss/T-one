def parse_number(value: Any) -> float | int | Any:
    if isinstance(value, (int, float)):
        return value
    text = str(value).replace(",", "").replace("$", "").replace("美金", "").replace("美元", "")
    match = re.search(r"-?\d+(?:\.\d+)?", text)
    if not match:
        return value
    number = float(match.group(0))
    unit_text = text[match.end(): match.end() + 3].lower()
    if "万" in unit_text:
        number *= 10_000
    elif "亿" in unit_text:
        number *= 100_000_000
    elif unit_text.startswith("k"):
        number *= 1_000
    elif unit_text.startswith("m"):
        number *= 1_000_000
    return int(number) if number.is_integer() else number


def parse_bool(value: Any) -> bool | Any:
    text = str(value).strip().lower()
    if text in {"是", "yes", "y", "true", "1", "出了", "出"}:
        return True
    if text in {"否", "no", "n", "false", "0", "没出", "未出"}:
        return False
    return value

