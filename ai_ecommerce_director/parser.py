def parse_key_values(text: str) -> dict[str, Any]:
    fields: dict[str, Any] = {}
    for raw_line in text.splitlines():
        line = raw_line.strip().strip("-").strip()
        if not line:
            continue
        _parse_line(line, fields)
    if not fields:
        _parse_line(text.strip(), fields)
    return normalize_fields(fields)


def _parse_line(line: str, fields: dict[str, Any]) -> None:
    matches = list(LABEL_RE.finditer(line))
    if not matches:
        return
    for index, match in enumerate(matches):
        label = match.group("label").lower()
        start = match.end()
        end = matches[index + 1].start() if index + 1 < len(matches) else len(line)
        value = line[start:end].strip().strip("，,;；")
        if not value:
            continue
        canonical = ALIAS_TO_FIELD.get(label)
        if canonical:
            fields[canonical] = value


